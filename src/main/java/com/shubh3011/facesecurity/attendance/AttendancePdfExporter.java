package com.shubh3011.facesecurity.attendance;

import com.lowagie.text.Document;
import com.lowagie.text.DocumentException;
import com.lowagie.text.Element;
import com.lowagie.text.Font;
import com.lowagie.text.FontFactory;
import com.lowagie.text.PageSize;
import com.lowagie.text.Paragraph;
import com.lowagie.text.Phrase;
import com.lowagie.text.pdf.PdfPCell;
import com.lowagie.text.pdf.PdfPTable;
import com.lowagie.text.pdf.PdfWriter;
import com.shubh3011.facesecurity.model.AttendanceRecord;
import com.shubh3011.facesecurity.model.AttendanceStats;
import com.shubh3011.facesecurity.model.AttendanceStatus;
import java.awt.Color;
import java.io.IOException;
import java.io.OutputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.LocalDate;
import java.time.ZoneId;
import java.time.format.DateTimeFormatter;
import java.util.List;
import java.util.Locale;

/** Renders a printable attendance sheet with OpenPDF. */
public final class AttendancePdfExporter {

    private static final DateTimeFormatter TIME_FORMAT = DateTimeFormatter.ofPattern("HH:mm:ss");
    private static final DateTimeFormatter DAY_FORMAT = DateTimeFormatter.ofPattern("EEEE, d MMMM yyyy");

    private static final Color INK = new Color(0x1F, 0x2A, 0x37);
    private static final Color MUTED = new Color(0x62, 0x6E, 0x7E);
    private static final Color HEADER_BG = new Color(0x1F, 0x2A, 0x37);
    private static final Color ROW_ALT = new Color(0xF1, 0xF5, 0xF9);
    private static final Color LATE = new Color(0xB4, 0x53, 0x09);

    private AttendancePdfExporter() {
    }

    public static void write(
            Path file,
            LocalDate day,
            List<AttendanceRecord> records,
            AttendanceStats stats,
            String title,
            ZoneId zone) throws IOException {

        if (file.getParent() != null) {
            Files.createDirectories(file.getParent());
        }

        Document document = new Document(PageSize.A4, 40, 40, 48, 40);
        try (OutputStream out = Files.newOutputStream(file)) {
            PdfWriter.getInstance(document, out);
            document.open();

            document.add(new Paragraph(title, font(FontFactory.HELVETICA_BOLD, 20, Font.BOLD, INK)));
            document.add(new Paragraph(day.format(DAY_FORMAT), font(FontFactory.HELVETICA, 11, Font.NORMAL, MUTED)));
            document.add(spacer(14));

            if (records.isEmpty()) {
                document.add(new Paragraph("No check-ins recorded for this day.",
                        font(FontFactory.HELVETICA_OBLIQUE, 11, Font.ITALIC, MUTED)));
            } else {
                document.add(buildTable(records, zone));
            }

            document.add(spacer(16));
            document.add(summary(stats));
            document.add(spacer(6));
            document.add(new Paragraph("Generated by Face Security Suite - offline face recognition, attendance and antivirus.",
                    font(FontFactory.HELVETICA, 8, Font.NORMAL, MUTED)));
        } catch (DocumentException e) {
            throw new IOException("could not generate the attendance PDF", e);
        } finally {
            document.close();
        }
    }

    private static PdfPTable buildTable(List<AttendanceRecord> records, ZoneId zone) throws DocumentException {
        PdfPTable table = new PdfPTable(new float[] { 0.9f, 3.0f, 1.7f, 1.3f, 1.4f, 1.4f });
        table.setWidthPercentage(100);
        table.setHeaderRows(1);

        addHeader(table, "#");
        addHeader(table, "Person");
        addHeader(table, "Time");
        addHeader(table, "Status");
        addHeader(table, "Confidence");
        addHeader(table, "Source");

        boolean alternate = false;
        int index = 1;
        for (AttendanceRecord record : records) {
            Color background = alternate ? ROW_ALT : Color.WHITE;
            Color statusColor = record.status() == AttendanceStatus.LATE ? LATE : INK;

            addCell(table, String.valueOf(index++), background, INK, Element.ALIGN_CENTER);
            addCell(table, record.personName(), background, INK, Element.ALIGN_LEFT);
            addCell(table, record.occurredAt().atZone(zone).format(TIME_FORMAT), background, INK, Element.ALIGN_CENTER);
            addCell(table, record.status().label(), background, statusColor, Element.ALIGN_CENTER);
            addCell(table, String.format(Locale.ROOT, "%.1f%%", record.confidence() * 100.0), background, INK,
                    Element.ALIGN_CENTER);
            addCell(table, record.source(), background, INK, Element.ALIGN_CENTER);
            alternate = !alternate;
        }
        return table;
    }

    private static void addHeader(PdfPTable table, String text) {
        PdfPCell cell = new PdfPCell(new Phrase(text, font(FontFactory.HELVETICA_BOLD, 9, Font.BOLD, Color.WHITE)));
        cell.setBackgroundColor(HEADER_BG);
        cell.setPadding(6f);
        cell.setBorderWidth(0f);
        table.addCell(cell);
    }

    private static void addCell(PdfPTable table, String text, Color background, Color foreground, int alignment) {
        PdfPCell cell = new PdfPCell(new Phrase(text, font(FontFactory.HELVETICA, 9, Font.NORMAL, foreground)));
        cell.setBackgroundColor(background);
        cell.setPadding(5f);
        cell.setHorizontalAlignment(alignment);
        cell.setBorderWidthBottom(0.4f);
        cell.setBorderColor(ROW_ALT);
        cell.setBorderWidthTop(0f);
        cell.setBorderWidthLeft(0f);
        cell.setBorderWidthRight(0f);
        table.addCell(cell);
    }

    private static Paragraph summary(AttendanceStats stats) {
        return new Paragraph(String.format(Locale.ROOT,
                "Check-ins %d   |   On time %d   |   Late %d   |   On-time rate %d%%",
                stats.total(), stats.present(), stats.late(), stats.onTimeRatePercent()),
                font(FontFactory.HELVETICA_BOLD, 10, Font.BOLD, INK));
    }

    private static com.lowagie.text.Font font(String family, float size, int style, Color color) {
        return FontFactory.getFont(family, size, style, color);
    }

    private static Paragraph spacer(float leading) {
        Paragraph paragraph = new Paragraph(" ");
        paragraph.setLeading(leading);
        return paragraph;
    }
}
